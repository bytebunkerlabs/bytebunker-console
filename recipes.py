def _render_ollama_win(p):
    port = int(p["port"]); lan = p.get("lan_ip") or "<host-lan-ip>"
    ps = f"""# Ollama on Windows — run in an ADMIN PowerShell (generated by the ByteBunker console)
winget install -e --id Ollama.Ollama            # skip if installed
[Environment]::SetEnvironmentVariable("OLLAMA_HOST", "0.0.0.0:{port}", "Machine")
[Environment]::SetEnvironmentVariable("OLLAMA_NUM_PARALLEL", "{int(p['parallel'])}", "Machine")
[Environment]::SetEnvironmentVariable("OLLAMA_KEEP_ALIVE", "24h", "Machine")
netsh advfirewall firewall add rule name="ollama-{port}" dir=in action=allow protocol=TCP localport={port}
Stop-Process -Name ollama,"ollama app" -ErrorAction SilentlyContinue; Start-Process "ollama" -ArgumentList "serve"
ollama pull {p['model']}
Invoke-RestMethod http://127.0.0.1:{port}/v1/models
"""
    served = p["model"].replace(":", "-").replace("/", "-")
    litellm = ("  - model_name: %s\n    litellm_params:\n      model: openai/%s\n      api_base: http://%s:%d/v1\n      api_key: \"not-needed\"\n"
               % (served, p["model"], lan, port))
    notes = ["Ollama serves one request at a time per model unless OLLAMA_NUM_PARALLEL is set; it does not batch like vLLM.",
             "Tool calling works for the tags listed above; hidden reasoning is off for Qwen3 when you pass think=false (the console does)."]
    return {"files": [("ollama-setup.ps1", ps)], "litellm_entry": litellm, "notes": notes,
            "api_base": "http://%s:%d/v1" % (lan, port), "model_name": served, "deploy_script": None}


