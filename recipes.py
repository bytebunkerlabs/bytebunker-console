"""Model deployment recipes — the console as the place where a model gets
deployed, not just used.

A recipe is a parameterised, reviewable plan: it renders the exact shell
script, service unit and litellm entry for one way of serving a model, so
the operator reads what will run before it runs. Deploying executes the
script over ssh on the target host and streams its output; registering
appends the litellm entry and restarts the gateway. Everything here is
plain text and stdlib — no templating engine, nothing hidden.
"""

from __future__ import annotations

import json
import shlex


def _p(name, label, default="", help="", kind="text", choices=None):
    d = {"name": name, "label": label, "default": default, "help": help, "kind": kind}
    if choices:
        d["choices"] = choices
    return d


