VLLM_CUDA = {
    "id": "vllm-cuda",
    "title": "vLLM on a CUDA GPU (Linux or WSL2)",
    "summary": "A small, fast model for agents on any NVIDIA card: uv venv + vLLM, tool calling on, "
               "a systemd user service that survives reboots, and a litellm entry so the console and "
               "the harness see it by name.",
    "target": "ssh",
    "params": [
        _p("host", "ssh host", "", "an ssh alias the console can reach without a password (e.g. agents-worker)"),
        _p("model", "Hugging Face model", "Qwen/Qwen3-4B-AWQ", "AWQ/GPTQ 4-bit fits 8 GB; Qwen3 and Llama 3.x support tool calling"),
        _p("served_name", "served model name", "qwen3-4b-fast", "the name litellm, the console and the harness will use"),
        _p("port", "port", "8001", "", "number"),
        _p("max_model_len", "context window (tokens)", "24576", "KV cache is what is left after the weights: 8 GB ≈ 25k tokens for a 4B AWQ model", "number"),
        _p("max_num_seqs", "concurrent sequences", "3", "how many agents can be served at once", "number"),
        _p("gpu_mem", "GPU memory fraction", "0.85", "leave room for the desktop on a shared card", "number"),
        _p("dtype", "dtype", "half", "half for Turing/Volta (no bf16); auto for Ampere+", "select", ["half", "auto", "bfloat16"]),
        _p("tool_parser", "tool-call parser", "hermes", "hermes for Qwen; llama3_json for Llama 3.x; mistral for Mistral", "select", ["hermes", "llama3_json", "mistral", "pythonic"]),
        _p("reasoning_parser", "reasoning parser", "qwen3", "strips hidden reasoning from replies; blank to disable", "select", ["qwen3", "deepseek_r1", ""]),
        _p("venv", "venv path", "~/vllm-env", ""),
        _p("lan_ip", "LAN address of the host", "", "for the litellm entry; on WSL2 this is the Windows box's LAN IP (needs a portproxy, see notes)"),
    ],
}


def _render_vllm_cuda(p):
    port = int(p["port"]); venv = p["venv"]
    args = [
        "serve", p["model"], "--host", "0.0.0.0", "--port", str(port),
        "--served-model-name", p["served_name"], "--max-model-len", str(int(p["max_model_len"])),
        "--max-num-seqs", str(int(p["max_num_seqs"])), "--gpu-memory-utilization", str(float(p["gpu_mem"])),
        "--dtype", p["dtype"], "--enable-auto-tool-choice", "--tool-call-parser", p["tool_parser"],
    ]
    if p.get("reasoning_parser"):
        args += ["--reasoning-parser", p["reasoning_parser"]]
    serve_sh = "#!/bin/bash\n# generated by the ByteBunker console\nexport PATH=/usr/lib/wsl/lib:$PATH\nexec %s/bin/vllm %s\n" % (
        venv, " ".join(shlex.quote(a) for a in args))
    install_sh = f"""#!/bin/bash
# vLLM on a CUDA GPU — generated by the ByteBunker console
set -e
export PATH="$HOME/.local/bin:/usr/lib/wsl/lib:$PATH"
if curl -s -m 3 http://127.0.0.1:{port}/v1/models 2>/dev/null | grep -q {shlex.quote(p['served_name'])}; then
  echo "== {p['served_name']} is already serving on port {port}; nothing to do (stop its service first to redeploy)"; exit 0
fi
echo "== gpu"; nvidia-smi --query-gpu=name,memory.total,driver_version,compute_cap --format=csv,noheader
command -v gcc >/dev/null || {{ echo "!! no C compiler: run  sudo apt install -y build-essential  (vLLM's Triton kernels need it)"; exit 2; }}
command -v uv >/dev/null || curl -LsSf https://astral.sh/uv/install.sh | sh
[ -x {venv}/bin/python ] || uv venv {venv} --python 3.12
uv pip install --python {venv}/bin/python vllm huggingface_hub
{venv}/bin/python -c "import vllm, torch; print('vllm', vllm.__version__, 'torch', torch.__version__, 'cuda', torch.cuda.is_available())"
{venv}/bin/python -c 'from huggingface_hub import snapshot_download; print(snapshot_download({json.dumps(p['model'])}))'
cat > ~/vllm-{p['served_name']}.sh <<'SERVE'
{serve_sh}SERVE
chmod +x ~/vllm-{p['served_name']}.sh
mkdir -p ~/.config/systemd/user
cat > ~/.config/systemd/user/vllm-{p['served_name']}.service <<'UNIT'
[Unit]
Description=vLLM {p['served_name']} ({p['model']})
After=network.target

[Service]
ExecStart=%h/vllm-{p['served_name']}.sh
Restart=on-failure
RestartSec=15
StandardOutput=append:%h/vllm-{p['served_name']}.log
StandardError=append:%h/vllm-{p['served_name']}.log

[Install]
WantedBy=default.target
UNIT
systemctl --user daemon-reload
systemctl --user enable --now vllm-{p['served_name']}.service
echo "== waiting for the engine"
for i in $(seq 1 36); do
  sleep 10
  if curl -s -m 3 http://127.0.0.1:{port}/v1/models | grep -q {shlex.quote(p['served_name'])}; then echo "== up: http://127.0.0.1:{port}/v1"; exit 0; fi
  grep -q "Engine core initialization failed" ~/vllm-{p['served_name']}.log 2>/dev/null && {{ echo "!! engine failed to start:"; grep -E "ERROR|Error" ~/vllm-{p['served_name']}.log | tail -5; exit 3; }}
done
echo "!! not up after 6 min; see ~/vllm-{p['served_name']}.log"; exit 4
"""
    lan = p.get("lan_ip") or "<host-lan-ip>"
    litellm = ("  - model_name: %s\n    litellm_params:\n      model: openai/%s\n      api_base: http://%s:%d/v1\n      api_key: \"not-needed\"\n"
               % (p["served_name"], p["served_name"], lan, port))
    notes = [
        "Rootless, no sudo: everything lives under the ssh user's home and a systemd USER unit (needs `loginctl enable-linger <user>` once).",
        "On WSL2 the service listens inside the VM. Expose it on the Windows LAN address in an admin PowerShell:\n"
        "  netsh interface portproxy add v4tov4 listenaddress=0.0.0.0 listenport=%d connectaddress=<wsl-ip> connectport=%d\n"
        "  netsh advfirewall firewall add rule name=\"vllm-%d\" dir=in action=allow protocol=TCP localport=%d" % (port, port, port, port),
        "Turing cards (RTX 20xx, compute 7.5) run vLLM's Triton attention backend, no FlashAttention; use dtype half.",
        "Then: Register in litellm (below) and set the harness `default_slave_model` to the served name.",
    ]
    return {"files": [("install-and-serve.sh", install_sh), ("serve.sh", serve_sh)],
            "litellm_entry": litellm, "notes": notes, "api_base": "http://%s:%d/v1" % (lan, port),
            "model_name": p["served_name"], "deploy_script": install_sh}


