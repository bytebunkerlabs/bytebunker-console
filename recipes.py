def _render_vllm_spark(p):
    port = int(p["port"]); tp = int(p["tp"])
    env = ""
    if tp > 1:
        env = "  -e VLLM_HOST_IP=%s -e TP_SOCKET_IFNAME=%s \\\n" % (p["head_ip"], p["ifname"])
    run = f"""#!/bin/bash
# vLLM on DGX Spark — generated by the ByteBunker console
set -e
docker rm -f serve_node 2>/dev/null || true
docker run -d --name serve_node --gpus all --ipc=host --network host --restart unless-stopped \\
  -v /models:/models -v ~/.cache/huggingface:/root/.cache/huggingface \\
{env}  {p['image']} \\
  vllm serve {shlex.quote(p['model'])} --host 0.0.0.0 --port {port} --served-model-name {shlex.quote(p['served_name'] or 'model')} \\
  --max-model-len {int(p['max_model_len'])} --tensor-parallel-size {tp} {p.get('extra') or ''}
echo "== waiting"; for i in $(seq 1 90); do sleep 10; curl -s -m 3 http://127.0.0.1:{port}/v1/models | grep -q model && {{ echo up; exit 0; }}; done
docker logs --tail 30 serve_node; exit 4
"""
    litellm = ("  - model_name: %s\n    litellm_params:\n      model: openai/%s\n      api_base: http://172.19.0.1:%d/v1\n      api_key: \"not-needed\"\n"
               % (p["served_name"] or "model", p["served_name"] or "model", port))
    notes = ["172.19.0.1 is the docker-bridge address litellm uses to reach the host's vLLM on the Spark; adjust if litellm runs elsewhere.",
             "Two-node tensor parallel needs the same command on the second Spark as a worker (ray) — follow NVIDIA's DGX Spark playbook for the worker side."]
    return {"files": [("run-spark.sh", run)], "litellm_entry": litellm, "notes": notes,
            "api_base": "http://<spark-lan-ip>:%d/v1" % port, "model_name": p["served_name"] or "model", "deploy_script": run}


# The DGX Sparks are NOT a console recipe: they are driven by `rack`
# (bytebunkerlabs/dgx-spark-serve), whose recipes/*.env already express solo
# vs tensor-parallel launches and gateway registration. The console wraps
# rack (see server.py /api/rack) instead of re-inventing it.
RECIPES = {r["id"]: r for r in (VLLM_CUDA, OLLAMA_WIN)}
_RENDER = {"vllm-cuda": _render_vllm_cuda, "ollama-windows": _render_ollama_win}


def catalog():
    return [{k: r[k] for k in ("id", "title", "summary", "target", "params")} for r in RECIPES.values()]


def render(recipe_id, params):
    r = RECIPES.get(recipe_id)
    if not r:
        raise KeyError("no such recipe")
    p = {x["name"]: str(params.get(x["name"], x["default"]) if params.get(x["name"], None) not in (None, "") else x["default"]) for x in r["params"]}
    for x in r["params"]:
        if x["kind"] == "number":
            float(p[x["name"]])          # ValueError surfaces as a 400
    out = _RENDER[recipe_id](p)
    out["params"] = p
    return out


def litellm_register_script(cfg_path, container, entry):
    """Idempotent append of a model entry to litellm's config + restart."""
    return (
        "set -e\nF=%s\ngrep -q %s \"$F\" && { echo 'already registered'; exit 0; }\n"
        "cp \"$F\" \"$F.bak-$(date +%%Y%%m%%d-%%H%%M%%S)\"\n"
        "python3 - <<'EOF'\nimport re\np=%s\ns=open(p).read()\nentry=%s\n"
        "m=re.search(r'(?m)^model_list:\\s*$', s)\n"
        "s = s[:m.end()] + '\\n' + entry + s[m.end():] if m else s + '\\nmodel_list:\\n' + entry\n"
        "open(p,'w').write(s)\nprint('entry added')\nEOF\n"
        "docker restart %s >/dev/null && sleep 8 && docker logs %s --since 30s 2>&1 | grep -iE 'error|Application startup complete' | tail -3\n"
        % (shlex.quote(cfg_path), shlex.quote("model_name: " + entry.split("model_name:")[1].split("\n")[0].strip()),
           json.dumps(cfg_path), json.dumps(entry), shlex.quote(container), shlex.quote(container)))
